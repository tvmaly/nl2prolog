"""Render normalized NL2Logic JSON (see variable_binding.py) as SWI-Prolog text.

Each formula becomes one fact::

    fol(s1, forall(X, implies(love(X, books), kind(X)))).

Quantified variables are real Prolog variables, shared between the binder and
its occurrences within the clause; constants are atoms.

Standard library only.
"""
from __future__ import annotations

import re
from typing import Any, Dict, List

_PLAIN_ATOM = re.compile(r"^[a-z][A-Za-z0-9_]*$")
_VARIABLE = re.compile(r"^[A-Z][A-Za-z0-9_]*$")
_BINARY = ("and", "or", "implies", "iff")


class EmitError(ValueError):
    """The document is not valid normalized JSON."""


def quote_atom(text: str) -> str:
    """Return ``text`` as a Prolog atom, quoting only when needed."""
    if _PLAIN_ATOM.match(text):
        return text
    escaped = text.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n")
    return f"'{escaped}'"


def _count_vars(node: Dict[str, Any], counts: Dict[str, int]) -> None:
    kind = node.get("type")
    if kind in ("forall", "exists"):
        name = node["var"]["prolog"]
        counts[name] = counts.get(name, 0) + 1
        _count_vars(node["body"], counts)
    elif kind in _BINARY:
        for arg in node["args"]:
            _count_vars(arg, counts)
    elif kind == "not":
        _count_vars(node["arg"], counts)
    elif kind == "atom":
        for term in node["args"]:
            if term.get("type") == "var":
                counts[term["prolog"]] = counts.get(term["prolog"], 0) + 1


def formula_to_prolog(formula: Dict[str, Any]) -> str:
    """Render one formula node as a Prolog term (no trailing full stop).

    Raises EmitError on a free variable or on a variable name reused by a
    nested binder -- either would silently change the meaning in Prolog.
    """
    counts: Dict[str, int] = {}
    try:
        _count_vars(formula, counts)
    except (KeyError, TypeError, AttributeError) as exc:
        raise EmitError(f"malformed formula: {exc!r}") from exc

    def var(name: str) -> str:
        # A variable that occurs once (an unused binder) is written _X so that
        # consulting the file does not raise a singleton warning.
        if counts.get(name) == 1 and "_" + name not in counts:
            return "_" + name
        return name

    def walk(node: Dict[str, Any], bound: List[str]) -> str:
        kind = node.get("type")
        if kind in ("forall", "exists"):
            name = node["var"]["prolog"]
            if not _VARIABLE.match(name):
                raise EmitError(f"not a Prolog variable name: {name!r}")
            if name in bound:
                raise EmitError(
                    f"variable {name} is bound twice in nested scopes; "
                    "binders must have distinct names")
            return f"{kind}({var(name)}, {walk(node['body'], bound + [name])})"
        if kind in _BINARY:
            left, right = node["args"]
            return f"{kind}({walk(left, bound)}, {walk(right, bound)})"
        if kind == "not":
            return f"not({walk(node['arg'], bound)})"
        if kind == "atom":
            args = []
            for term in node["args"]:
                if term.get("type") == "var":
                    if term["prolog"] not in bound:
                        raise EmitError(f"free variable {term['prolog']}")
                    args.append(var(term["prolog"]))
                elif term.get("type") == "const":
                    args.append(quote_atom(term["atom"]))
                else:
                    raise EmitError(f"unknown term type {term.get('type')!r}")
            pred = quote_atom(node["pred"])
            return f"{pred}({', '.join(args)})" if args else pred
        raise EmitError(f"unknown formula type {kind!r}")

    try:
        return walk(formula, [])
    except (KeyError, TypeError, ValueError) as exc:
        if isinstance(exc, EmitError):
            raise
        raise EmitError(f"malformed formula: {exc!r}") from exc


def _comment(text: str) -> str:
    return "% " + " ".join(str(text).split())


def to_prolog(doc: Dict[str, Any], *, functor: str = "fol",
              diagnostics: bool = True) -> str:
    """Render a normalized document as a consultable Prolog file."""
    if not isinstance(doc, dict) or "formulas" not in doc:
        raise EmitError("expected a normalized document with 'formulas'")
    lines = [f"% Generated by nl2logic-prolog ({doc.get('schema', '?')})."]
    if doc.get("source"):
        lines.append(_comment(f"source: {doc['source']}"))
    if diagnostics:
        for d in doc.get("diagnostics", []):
            lines.append(_comment(
                f"{d.get('severity')} [{d.get('code')}] {d.get('formula')}: "
                f"{d.get('message')}"))
    head = quote_atom(functor)
    for entry in doc["formulas"]:
        lines.append(
            f"{head}({quote_atom(str(entry['id']))}, "
            f"{formula_to_prolog(entry['formula'])}).")
    return "\n".join(lines) + "\n"
